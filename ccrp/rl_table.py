"""Paper table for the synthetic RL study, from results/rl/raw_<setting>.json (paired by seed).

  python -m ccrp.rl_table --out results/rl
"""
from __future__ import annotations

import argparse
import json
import os

import numpy as np

SETTINGS = [("validation", "Validation"), ("long", "Long horizon"), ("large-and6", "Large")]
# (row label, key per setting); Team-Plan and always-deep use the Bayesian rule with belief rollouts
ROWS = [
    ("Never intervene", {"*": "never"}),
    ("Partner-blind, one step", {"*": "blind_one_step"}),
    ("Cause-aware exact, one step", {"*": "one_step"}),
    ("Cause-aware exact, multi-step", {"*": "exact"}),
    ("Learned value $V_\\phi$, greedy", {"*": "rl_greedy"}),
    ("\\method{} ($V_\\phi$ + certificate + deliberation)", {"validation": "teamplan_bayes_eps0.02", "long": "teamplan",
                                                         "large-and6": "teamplan_bayes_eps0.02"}),
    ("Deliberate at every decision", {"validation": "always_deep_bayes", "long": "always_deep",
                                      "large-and6": "always_deep_bayes"}),
    ("Deliberate, best rollout mean", {"validation": "always_deep_belief"}),
    ("Full information (exact)", {"*": "full_info"}),
]


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--out", default="results/rl"); a = ap.parse_args()
    raw = {s: json.load(open(os.path.join(a.out, f"raw_{s}.json"))) for s, _ in SETTINGS
           if os.path.exists(os.path.join(a.out, f"raw_{s}.json"))}
    key = lambda row, s: row[1].get(s, row[1].get("*"))
    summary = {}
    for s, name in SETTINGS:
        d = raw.get(s, {}); g = np.array(d["rl_greedy"]["reward"]) if "rl_greedy" in d else None
        tp = np.array(d[key(ROWS[5], s)]["reward"]) if key(ROWS[5], s) in d else None
        summary[s] = {}
        for row in ROWS:
            k = key(row, s)
            if k is None or k not in d:
                continue
            r = np.array(d[k]["reward"]); n = len(r)
            e = {"key": k, "n": n, "reward": float(r.mean()), "se": float(r.std(ddof=1) / np.sqrt(n)),
                 "success": float(np.mean(d[k]["success"])), "rollouts": float(np.mean(d[k]["rollouts"]))}
            for ref_name, ref in (("vs_greedy", g), ("vs_teamplan", tp)):
                if ref is not None and len(ref) == n:
                    diff = r - ref; e[ref_name] = [float(diff.mean()), float(diff.std(ddof=1) / np.sqrt(n))]
            summary[s][row[0]] = e
    json.dump(summary, open(os.path.join(a.out, "rl_table.json"), "w"), indent=1)
    print("% rows: reward (rollouts per episode); generated by ccrp/rl_table.py")
    for row in ROWS:
        cells = []
        for s, _ in SETTINGS:
            e = summary[s].get(row[0])
            if e is None:
                cells.append("--"); continue
            c = f"{e['reward']:.3f}".lstrip("0")
            if e["rollouts"] > 0:
                c += f" ({e['rollouts']:.0f})"
            cells.append(c)
        print(f"    {row[0]} & " + " & ".join(cells) + r" \\")
    print()
    for s, _ in SETTINGS:
        for lab, e in summary[s].items():
            extra = " ".join(f"{k} {v[0]:+.3f}+-{v[1]:.3f}" for k, v in e.items() if k.startswith("vs_"))
            print(f"{s:11s} {lab[:44]:44s} n={e['n']} {e['reward']:.3f} succ {e['success']:.2f} roll {e['rollouts']:.0f} {extra}")


if __name__ == "__main__":
    main()
